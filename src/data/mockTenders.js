// Helper to get all tenders from localStorage or fallback
export function getSavedTenders() {
  try {
    const saved = localStorage.getItem('tendersearch_all_tenders');
    if (saved) {
      return JSON.parse(saved);
    }
  } catch (e) {
    console.warn("Could not read localStorage", e);
  }
  return initialMockTenders;
}

// Helper to save tenders
export function saveTenders(tenders) {
  try {
    localStorage.setItem('tendersearch_all_tenders', JSON.stringify(tenders));
  } catch (e) {
    console.warn("Could not write localStorage", e);
  }
}
